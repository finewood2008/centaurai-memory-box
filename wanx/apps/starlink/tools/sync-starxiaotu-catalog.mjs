import {readFile,writeFile} from 'node:fs/promises';
// The same catalog ships in the gate wheel and the assembled client.
const input=new URL('../../../shared/packages/local-data-gate/centuarai_local_data_gate/starxiaotu_catalog.json',import.meta.url);
export async function syncStarxiaotuCatalog({check=false}={}) {
  const catalog=JSON.parse(await readFile(input,'utf8'));
  const output='// Generated by tools/sync-starxiaotu-catalog.mjs; edit the shared catalog.\nexport default '+JSON.stringify(catalog,null,2)+';\n';
  const target=new URL('../shared/starxiaotu-catalog.mjs',import.meta.url);
  if (check) {
    // Git may check out the generated file with Windows line endings.
    const actual = (await readFile(target, 'utf8')).replaceAll('\r\n', '\n');
    if (actual !== output) throw new Error('Starxiaotu catalog is stale');
  } else {
    await writeFile(target, output);
  }
}
