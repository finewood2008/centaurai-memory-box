import childProcess from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readFileSync, readlinkSync, realpathSync } from "node:fs";
import path from "node:path";

// Shared assembly inputs are part of each edition's release provenance.
function sourcePaths(root) {
  const canonicalRoot = realpathSync(root);
  const repository = realpathSync(childProcess.execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: root, encoding: "utf8" }).trim());
  return [".", ...["../builder", "../starlink",
    "../personal-client/shell/personal-space.mjs", "../personal-client/shell/space-drive-routing.mjs",
    "../personal-client/shell/space-annotation-service.mjs", "../personal-client/shell/space-annotations.mjs",
    "../personal-client/shell/space-annotation-workbench.mjs", "../personal-client/shell/annotation-workbench-contract.mjs",
    "../personal-client/shell/annotation-content.mjs", "../personal-client/shell/annotation-content-worker.mjs",
    "../personal-client/local-ui/renderer/personal-space.js", "../../tools/npm-command.mjs"].filter(relative=>{
    const absolute=path.resolve(canonicalRoot,relative), inside=path.relative(repository,absolute);
    return existsSync(absolute) && !inside.startsWith("..") && !path.isAbsolute(inside);
  })];
}

// Client and shared sources include packaging recipes and dependency
// locks. Ignored build outputs are regenerated by the packaging entry points.
export function clientBuildSource(root, { formal = true, expectedCommit } = {}) {
  const git = args => childProcess.execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  const sourceCommit = git(["rev-parse", "HEAD"]);
  if (!/^(?:[a-f0-9]{40}|[a-f0-9]{64})$/.test(sourceCommit)) throw new Error("CLIENT_SOURCE_COMMIT_INVALID");
  const sourceDirty = Boolean(git(["status", "--porcelain=v1", "--untracked-files=all", "--ignore-submodules=none", "--", ...sourcePaths(root)]));
  if (formal && sourceDirty) throw new Error("CLIENT_SOURCE_TREE_DIRTY: 正式构建需要已提交且没有未跟踪文件的客户端源码。");
  if (expectedCommit && sourceCommit !== expectedCommit) throw new Error("CLIENT_SOURCE_CHANGED_DURING_BUILD");
  return { sourceCommit: sourceDirty ? null : sourceCommit, sourceDirty };
}

// Test builds may intentionally include a reviewed dirty workspace. Record the
// precise source snapshot without claiming it is the committed release source.
export function clientTestSourceSnapshot(root) {
  const files = childProcess.execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", ...sourcePaths(root)],
    { cwd: root, encoding: "utf8" }).split("\0").filter(Boolean).sort();
  const hash = createHash("sha256");
  for (const name of [...new Set(files)]) {
    const file = path.join(root, name);
    hash.update(name).update("\0");
    try {
      const entry = lstatSync(file);
      hash.update(String(entry.mode & 0o777)).update("\0");
      hash.update(entry.isSymbolicLink() ? `symlink:${readlinkSync(file)}` : readFileSync(file));
    } catch (error) { if (error.code !== "ENOENT") throw error; hash.update("deleted"); }
    hash.update("\0");
  }
  return hash.digest("hex");
}
