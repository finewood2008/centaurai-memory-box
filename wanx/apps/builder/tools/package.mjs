import{build}from'esbuild';
import{buildBuilderBrand}from'./build-brand.mjs';
import{mkdir,copyFile,writeFile,readFile,cp,rm}from'node:fs/promises';
import path from'node:path';
import{fileURLToPath}from'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));
const version=JSON.parse(await readFile(path.join(root,'package.json'),'utf8')).version;
const studio=path.join(root,'release/wanx-studio-'+version);
await buildBuilderBrand(root,path.join(studio,'assets'));
await copyFile(path.join(root,'ui/assets/centaurai-mark.png'),path.join(studio,'assets/centaurai-mark.png'));
await mkdir(path.join(studio,'shell'),{recursive:true});
await build({entryPoints:[path.join(root,'shell/main.cjs')],bundle:true,platform:'node',format:'cjs',outfile:path.join(studio,'shell/main.cjs'),external:['electron'],logLevel:'silent'});
await copyFile(path.join(root,'shell/preload.cjs'),path.join(studio,'shell/preload.cjs'));
await rm(path.join(studio,'ui'),{recursive:true,force:true});
await cp(path.join(root,'dist/ui'),path.join(studio,'ui'),{recursive:true});
await writeFile(path.join(studio,'application.manifest.json'),JSON.stringify({applicationId:'ai.wanx.studio',name:'万象·开物',version,protocolVersion:1,runtime:'electron',launchMode:'shared',entrypoint:'shell/main.cjs',description:'WanX Builder · 从想法到应用，持续构建、试用和改进。'},null,2));
console.log(JSON.stringify({studio}));
